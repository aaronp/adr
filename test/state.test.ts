import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createInitialState, reducer, type Action, type State } from '../src/ui/state.ts';
import { parseLedger, serializeLedger } from '../src/core/markdown.ts';
import { readSample } from './helpers.ts';

const TODAY = '2026-10-24';
const fresh = (over: Partial<{ storedMarkdown: string | null; storedTheme: string | null }> = {}): State =>
  createInitialState({ storedMarkdown: null, storedTheme: null, sampleMarkdown: readSample(), ...over });
const run = (s: State, ...actions: Action[]): State => actions.reduce(reducer, s);

test('starts from the sample when nothing is stored', () => {
  const s = fresh();
  assert.equal(s.adrs.length, 6);
  assert.equal(s.screen.kind, 'dashboard');
  assert.equal(s.md.text, s.md.base);
});

test('a stored file that no longer parses opens the markdown view with the error (no silent fallback)', () => {
  const s = fresh({ storedMarkdown: 'garbage' });
  assert.equal(s.adrs.length, 0);
  assert.equal(s.screen.kind, 'markdown');
  assert.equal(s.md.text, 'garbage');
  assert.match(s.md.error?.message ?? '', /could not be loaded/);
  assert.equal(s.md.error?.line, 1);
});

test('unknown stored theme is reported', () => {
  const s = fresh({ storedTheme: 'neon' });
  assert.equal(s.theme, 'paper');
  assert.match(s.toast?.text ?? '', /neon/);
});

test('editing via the form updates the markdown', () => {
  const s = run(
    fresh(),
    { type: 'edit/start', id: 'ADR-0013' },
    { type: 'edit/update', update: (d) => ({ ...d, title: 'Adopt TypeBox for service contracts' }) },
    { type: 'edit/save' }
  );
  assert.equal(s.screen.kind, 'view');
  assert.match(s.md.text, /title: Adopt TypeBox for service contracts/);
  assert.equal(s.md.text, s.md.base);
});

test('invalid save is refused and flagged', () => {
  const s = run(fresh(), { type: 'edit/start', id: 'ADR-0012' }, { type: 'edit/update', update: (d) => ({ ...d, decision: '' }) }, { type: 'edit/save' });
  assert.equal(s.screen.kind, 'edit');
  assert.ok(s.screen.kind === 'edit' && s.screen.triedSave);
  assert.equal(s.adrs.find((a) => a.id === 'ADR-0012')?.decision, 'kafka');
});

test('new ADR gets the next id and is only saved when valid', () => {
  const s = run(fresh(), { type: 'edit/new', today: TODAY });
  assert.ok(s.screen.kind === 'edit' && s.screen.draft.id === 'ADR-0015' && s.screen.draft.date === TODAY);
  const tried = run(s, { type: 'edit/save' });
  assert.equal(tried.adrs.length, 6);
});

test('ids generated by the reducer are deterministic', () => {
  const a = run(fresh(), { type: 'edit/new', today: TODAY }, { type: 'edit/addCriterion' }, { type: 'edit/addSolution' });
  const b = run(fresh(), { type: 'edit/new', today: TODAY }, { type: 'edit/addCriterion' }, { type: 'edit/addSolution' });
  assert.deepEqual(a.screen, b.screen);
});

test('markdown apply replaces records; a bad edit changes nothing', () => {
  const s0 = fresh();
  const edited = s0.md.text.replace('title: Store web sessions in Redis', 'title: Keep web sessions in Redis');
  const ok = run(s0, { type: 'nav/markdown', focusId: null }, { type: 'md/text', value: edited }, { type: 'md/apply' });
  assert.equal(ok.adrs.find((a) => a.id === 'ADR-0006')?.title, 'Keep web sessions in Redis');
  assert.equal(ok.md.error, null);

  const bad = run(ok, { type: 'md/text', value: ok.md.text.replace('weight | description |', 'weight |') }, { type: 'md/apply' });
  assert.deepEqual(bad.adrs, ok.adrs);
  assert.notEqual(bad.md.error, null);
  const back = run(bad, { type: 'md/discard' });
  assert.equal(back.md.text, ok.md.base);
});

test('opening a file loads it; the result is the normal form', () => {
  const one = serializeLedger(parseLedger(readSample()).slice(0, 1));
  const s = run(fresh(), { type: 'md/load', text: one, source: 'mine.md' });
  assert.equal(s.adrs.length, 1);
  assert.match(s.md.notice ?? '', /Loaded mine\.md: 1 record/);
});

test('delete removes the record from the file', () => {
  const s = run(fresh(), { type: 'edit/start', id: 'ADR-0014' }, { type: 'edit/delete' });
  assert.equal(s.adrs.some((a) => a.id === 'ADR-0014'), false);
  assert.doesNotMatch(s.md.text, /ADR-0014/);
});

test('a ?src= file wins over stored markdown', () => {
  const one = serializeLedger(parseLedger(readSample()).slice(0, 1));
  const s = createInitialState({ source: { url: 'https://example.org/decisions.md', markdown: one }, storedMarkdown: readSample(), storedTheme: null, sampleMarkdown: readSample() });
  assert.equal(s.adrs.length, 1);
  assert.equal(s.screen.kind, 'dashboard');
});

test('a ?src= file that does not parse opens the markdown view and names the URL', () => {
  const s = createInitialState({ source: { url: 'https://example.org/bad.md', markdown: 'not a ledger' }, storedMarkdown: null, storedTheme: null, sampleMarkdown: readSample() });
  assert.equal(s.screen.kind, 'markdown');
  assert.equal(s.adrs.length, 0);
  assert.match(s.md.error?.message ?? '', /https:\/\/example\.org\/bad\.md could not be loaded/);
});

test('the Open dialog shows, hides, and closes once a file loads (or fails to parse)', () => {
  const shown = run(fresh(), { type: 'open/show' });
  assert.equal(shown.openDialog, true);
  assert.equal(run(shown, { type: 'open/hide' }).openDialog, false);
  const one = serializeLedger(parseLedger(readSample()).slice(0, 1));
  assert.equal(run(shown, { type: 'md/load', text: one, source: 'https://example.org/d.md' }).openDialog, false);
  const bad = run(shown, { type: 'md/load', text: 'nope', source: 'x.md' });
  assert.equal(bad.openDialog, false);
  assert.equal(bad.screen.kind, 'markdown');
});
